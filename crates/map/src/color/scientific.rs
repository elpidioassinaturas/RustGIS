//!   Cividis: Jamie R. Nuñez, Christopher R. Anderton and Ryan S. Renslow, as matplotlib ships them.
//! - Turbo: Anton Mikhailov, Copyright 2019 Google LLC (Apache-2.0).
//! - Batlow, Vik, Roma and Oleron: Scientific colour maps, Copyright (c) 2020 Fabio Crameri (MIT).
//! - Balance, Haline, Deep and Topo: cmocean, Copyright (c) 2015 Kristen M. Thyng (MIT).
//!
//! Oleron and Topo change colour abruptly at sea level, halfway along: each is two runs of
//! [`SPLIT`] stops, below and above it.

const fn h(c: u32) -> [u8; 3] {
    [(c >> 16) as u8, (c >> 8) as u8, c as u8]
}

/// Ramps made of two runs of stops hold this many in each, meeting at 0.5 without blending.
pub(super) const SPLIT: usize = 17;

